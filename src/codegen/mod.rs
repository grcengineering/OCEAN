/// Flatten a CheckDefinition into a Handlebars-compatible JSON context.
fn build_context(def: &CheckDefinition) -> serde_json::Value {
    let credentials: Vec<_> = def
        .credentials
        .iter()
        .map(|(name, cred)| {
            json!({
                "name": name,
                "type": cred.cred_type,
                "required": cred.required,
            })
        })
        .collect();

    let inputs: Vec<_> = def
        .inputs
        .iter()
        .map(|(name, inp)| {
            json!({
                "name": name,
                "env": inp.env,
                "description": inp.description,
                "required": inp.required,
            })
        })
        .collect();

    let steps: Vec<_> = def
        .steps
        .iter()
        .enumerate()
        .map(|(i, step)| {
            let method = &step.request.method;
            let url = &step.request.url;
            // Strip https://api.github.com prefix for gh-cli path
            let gh_path = url
                .strip_prefix("https://api.github.com/")
                .unwrap_or(url)
                .to_string();
            let headers: Vec<_> = step
                .request
                .headers
                .iter()
                .map(|(k, v)| json!({ "key": k, "value": v }))
                .collect();
            json!({
                "id": step.id,
                "method": method,
                "url": url,
                "gh_path": gh_path,
                "headers": headers,
                "index": i,
            })
        })
        .collect();

    let remediation_cli = def
        .remediation
        .as_ref()
        .and_then(|r| r.cli.as_ref())
        .map(|c| c.command.clone());

    json!({
        "check": {
            "id": def.id,
            "name": def.name,
            "description": def.description.trim(),
            "source": def.source,
            "profile": def.profile,
            "tags": def.tags,
            "credentials": credentials,
            "inputs": inputs,
            "steps": steps,
            "remediation_cli": remediation_cli,
            "references": {
                "cis": format_string_or_vec(&def.references.cis),
                "nist": format_string_or_vec(&def.references.nist),
                "soc2": format_string_or_vec(&def.references.soc2),
                "iso27001": format_string_or_vec(&def.references.iso27001),
                "pci_dss": format_string_or_vec(&def.references.pci_dss),
                "disa_stig": format_string_or_vec(&def.references.disa_stig),
            },
        }
    })
}

fn format_string_or_vec(val: &crate::check::definition::StringOrVec) -> String {
    match val {
        crate::check::definition::StringOrVec::One(s) => s.clone(),
        crate::check::definition::StringOrVec::Many(v) => v.join(", "),
        crate::check::definition::StringOrVec::None => String::new(),
    }
}

// ─── Generation ───────────────────────────────────────────────────────────────

/// Generate code packs for all checks in `checks_dir` for the given target.
///
/// Returns the number of files written (or that would be written in `--diff` mode).
pub fn generate<W: Write>(
    out: &mut W,
    checks_dir: &Path,
    target: &BuildTarget,
    output_dir: &Path,
    validate_only: bool,
    diff_only: bool,
    filter: Option<&str>,
) -> Result<usize> {
    let defs = load_definitions_from_dir(checks_dir);

    let filtered: Vec<&CheckDefinition> = defs
        .iter()
        .filter(|d| filter.is_none_or(|f| d.id.starts_with(f) || d.source == f))
        .collect();

    if filtered.is_empty() {
        writeln!(out, "No checks found in {}", checks_dir.display())?;
        return Ok(0);
    }

    let mut hb = Handlebars::new();
    hb.set_strict_mode(false);

    let template_src = match target {
        BuildTarget::ApiScript => API_SCRIPT_TEMPLATE,
        BuildTarget::GhCli => GH_CLI_TEMPLATE,
        BuildTarget::PythonSdk => PYTHON_SDK_TEMPLATE,
        BuildTarget::GoSdk => GO_SDK_TEMPLATE,
        BuildTarget::OpaRego => OPA_REGO_TEMPLATE,
        BuildTarget::Terraform => TERRAFORM_TEMPLATE,
        BuildTarget::SigmaRule => SIGMA_RULE_TEMPLATE,
    };

    hb.register_template_string("pack", template_src)
        .context("register Handlebars template")?;

    if validate_only {
        writeln!(out, "Validated {} check(s) — templates OK", filtered.len())?;
        return Ok(filtered.len());
    }

    if !diff_only {
        std::fs::create_dir_all(output_dir)
            .with_context(|| format!("create output dir {}", output_dir.display()))?;
    }

    let mut written = 0;
    for def in &filtered {
        if def.implementation == "native" {
            let filename = format!("{}.stub.{}", def.id.to_lowercase(), target.extension());
            let stub = format!(
                "#!/usr/bin/env bash\n# {} — {}\n# This check requires OCEAN CLI (native implementation).\necho \"Run: ocean observe {}\"\n",
                def.id, def.name, def.id
            );
            write_or_diff(out, output_dir, &filename, &stub, diff_only)?;
            written += 1;
            continue;
        }

        let ctx = build_context(def);
        let rendered = hb
            .render("pack", &ctx)
            .with_context(|| format!("render template for {}", def.id))?;

        let filename = format!(
            "{}.{}",
            def.id.to_lowercase().replace('.', "-"),
            target.extension()
        );
        write_or_diff(out, output_dir, &filename, &rendered, diff_only)?;
        written += 1;
    }

    if diff_only {
        writeln!(out, "Would write {written} file(s) to {}", output_dir.display())?;
    } else {
        writeln!(
            out,
            "Generated {written} {} pack(s) → {}",
            target.slug(),
            output_dir.display()
        )?;
    }

    Ok(written)
}

fn write_or_diff<W: Write>(
    out: &mut W,
    dir: &Path,
    filename: &str,
    content: &str,
    diff_only: bool,
) -> Result<()> {
    if diff_only {
        writeln!(out, "  + {filename}")?;
        return Ok(());
    }
    let path = dir.join(filename);
    std::fs::write(&path, content)
        .with_context(|| format!("write {}", path.display()))?;
    // Make scripts executable
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(&path)?.permissions();
        perms.set_mode(0o755);
        std::fs::set_permissions(&path, perms)?;
    }
    writeln!(out, "  ✓ {filename}")?;
    Ok(())
}

