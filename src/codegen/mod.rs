// Code pack generation for `ocean build`.
//
// Compiles `.check.yaml` files into standalone, human-readable scripts using
// Handlebars templates. Generated scripts are checked into packs/ so users
// can browse, audit, and run them without installing OCEAN.
//
// Supported targets:
//   api-script  — Bash + curl + jq (universal)
//   gh-cli      — Bash + GitHub CLI (gh)

use std::io::Write;
use std::path::Path;

use anyhow::{Context, Result};
use handlebars::Handlebars;
use serde_json::json;

use crate::check::definition::CheckDefinition;
use crate::check::loader::load_definitions_from_dir;

// ─── Target ───────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BuildTarget {
    ApiScript,
    GhCli,
    PythonSdk,
    GoSdk,
    OpaRego,
    Terraform,
    SigmaRule,
}

impl BuildTarget {
    pub fn from_str(s: &str) -> Result<Self> {
        match s.to_lowercase().as_str() {
            "api-script" | "api_script" => Ok(Self::ApiScript),
            "gh-cli" | "gh_cli" => Ok(Self::GhCli),
            "python-sdk" | "python_sdk" | "python" => Ok(Self::PythonSdk),
            "go-sdk" | "go_sdk" | "go" => Ok(Self::GoSdk),
            "opa-rego" | "opa_rego" | "rego" => Ok(Self::OpaRego),
            "terraform" | "tf" => Ok(Self::Terraform),
            "sigma-rule" | "sigma_rule" | "sigma" => Ok(Self::SigmaRule),
            other => Err(anyhow::anyhow!(
                "unknown build target '{other}'; expected: api-script, gh-cli, python-sdk, go-sdk, opa-rego, terraform, sigma-rule"
            )),
        }
    }

    pub fn slug(&self) -> &'static str {
        match self {
            Self::ApiScript => "api-script",
            Self::GhCli => "gh-cli",
            Self::PythonSdk => "python-sdk",
            Self::GoSdk => "go-sdk",
            Self::OpaRego => "opa-rego",
            Self::Terraform => "terraform",
            Self::SigmaRule => "sigma-rule",
        }
    }

    pub fn extension(&self) -> &'static str {
        match self {
            Self::ApiScript | Self::GhCli => "sh",
            Self::PythonSdk => "py",
            Self::GoSdk => "go",
            Self::OpaRego => "rego",
            Self::Terraform => "tf",
            Self::SigmaRule => "yml",
        }
    }
}

